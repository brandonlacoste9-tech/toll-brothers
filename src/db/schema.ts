import { boolean, integer, pgTable, text, timestamp } from "drizzle-orm/pg-core";

export const communities = pgTable("communities", {
  slug: text("slug").primaryKey(),
  name: text("name").notNull(),
  city: text("city").notNull(),
  state: text("state").notNull(),
  region: text("region").notNull(),
  kind: text("kind").notNull(),
  homeType: text("home_type").notNull(),
  priceFrom: integer("price_from"),
  priceTo: integer("price_to"),
  sqftFrom: integer("sqft_from"),
  sqftTo: integer("sqft_to"),
  style: text("style").notNull(),
  image: text("image").notNull(),
  blurb: text("blurb").notNull(),
  address: text("address"),
  school: text("school"),
  liveUrl: text("live_url").notNull(),
  advisorPhone: text("advisor_phone").notNull(),
  advisorHref: text("advisor_href").notNull(),
  advisorLabel: text("advisor_label").notNull(),
});

export const plans = pgTable("plans", {
  slug: text("slug").primaryKey(),
  communitySlug: text("community_slug").notNull(),
  name: text("name").notNull(),
  collection: text("collection").notNull(),
  beds: text("beds").notNull(),
  baths: text("baths").notNull(),
  halfBaths: text("half_baths").notNull(),
  garage: text("garage").notNull(),
  sqft: integer("sqft").notNull(),
  stories: text("stories").notNull(),
  priceFrom: integer("price_from"),
  style: text("style").notNull(),
  image: text("image").notNull(),
  blurb: text("blurb").notNull(),
  highlights: text("highlights").notNull(),
  liveUrl: text("live_url").notNull(),
});

export const homes = pgTable("homes", {
  slug: text("slug").primaryKey(),
  communitySlug: text("community_slug").notNull(),
  planSlug: text("plan_slug"),
  name: text("name").notNull(),
  status: text("status").notNull(),
  address: text("address").notNull(),
  beds: integer("beds").notNull(),
  baths: integer("baths").notNull(),
  halfBaths: integer("half_baths").notNull(),
  garage: integer("garage").notNull(),
  sqft: integer("sqft").notNull(),
  stories: integer("stories").notNull(),
  price: integer("price").notNull(),
  style: text("style").notNull(),
  elevation: text("elevation").notNull(),
  image: text("image").notNull(),
  moveDate: text("move_date"),
  tags: text("tags").notNull(),
  liveUrl: text("live_url").notNull(),
});

export const collections = pgTable("collections", {
  slug: text("slug").primaryKey(),
  name: text("name").notNull(),
  tags: text("tags").notNull(),
  image: text("image").notNull(),
  blurb: text("blurb").notNull(),
});

export const inquiries = pgTable("inquiries", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull(),
  phone: text("phone"),
  region: text("region").notNull(),
  interest: text("interest").notNull(),
  communitySlug: text("community_slug"),
  homeSlug: text("home_slug"),
  message: text("message"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull(),
  routedPhone: text("routed_phone").notNull(),
  liveUrl: text("live_url").notNull(),
  stored: boolean("stored").notNull(),
});
